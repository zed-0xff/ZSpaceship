-- ZSRoom class for ZSpaceship mod
-- Represents a room with utility methods

-- ZSRoom class
ZSRoom = ZSRoom or {}
ZSRoom.__index = ZSRoom

ZSRoom.State = {
    UNKNOWN = "unknown",
    CHECKING = "checking",
    SEALED = "sealed",
    BREACHED = "breached",
}

-- Static helper: Generate string key from square coordinates
function ZSRoom.getSquareKey(sq)
    if not sq then return nil end
    local x, y, z = sq:getX(), sq:getY(), sq:getZ()
    if x and y and z then
        return x .. ":" .. y .. ":" .. z
    end
    return nil
end

-- Static helper: Generate string key from coordinates
function ZSRoom.getSquareKeyFromCoords(x, y, z)
    if x and y and z then
        return x .. ":" .. y .. ":" .. z
    end
    return nil
end

-- Static helper: Check if square is open space
function ZSRoom.isOpenSpace(sq)
    if not sq then return false end
    local x, y = sq:getX(), sq:getY()
    if ZSpaceship and ZSpaceship.isInSpace and x and y then
        if ZSpaceship.isInSpace(x, y) then return true end
    end
    local hasFloor = sq.getFloor and sq:getFloor() ~= nil
    local hasRoof = sq.getRoof and sq:getRoof() ~= nil
    return not hasFloor or not hasRoof
end

-- Whitelist of airtight wall tiles
-- These are populated by ZSpaceship_MapData.lua (generated by compiler.rb)
ZSRoom.AIRTIGHT_WALLS_NS = ZSRoom.AIRTIGHT_WALLS_NS or {}
ZSRoom.AIRTIGHT_WALLS_EW = ZSRoom.AIRTIGHT_WALLS_EW or {}

-- Constructor: create a new ZSRoom instance from a square or room object
function ZSRoom:new(squareOrRoom)
    local instance = {}
    setmetatable(instance, ZSRoom)
    
    local isoRoom = nil
    if squareOrRoom then
        if squareOrRoom.getRoom then
            -- It's a square
            isoRoom = squareOrRoom:getRoom()
        else
            -- Assume it's a isoRoom object
            isoRoom = squareOrRoom
        end
    end
    
    instance.isoRoom = isoRoom
    instance.squares = nil
    
    -- Cache properties (initialized to nil, computed on demand)
    instance.airtight = nil
    instance.connections = {}  -- { [roomId] = { door = door object, square = square, adjSquare = adjSquare } }
    instance.doors = nil  -- Cached doors list
    instance.vacuumState = nil  -- Cached vacuum breach state (true = breached, false = sealed)

    self:update()
    
    return instance
end

-- Get the room ID
function ZSRoom:getID()
    return self.isoRoom and tostring(self.isoRoom) or nil
end

-- Check if the room is valid
function ZSRoom:isValid()
    if not self.isoRoom or not self.squares then return false end
    -- Check if table has any entries
    for _ in pairs(self.squares) do
        return true
    end
    return false
end

-- Update room properties (open space, missing walls, airtight, connections)
function ZSRoom:update()
    if self.isoRoom and self.isoRoom.getSquares and self.isoRoom:getSquares():size() > 0 then
        local javaSquares = self.isoRoom:getSquares()
        -- Convert Java collection to Lua table with key = "x:y:z"
        self.squares = {}
        if javaSquares then
            for i = 0, javaSquares:size() - 1 do
                local sq = javaSquares:get(i)
                if sq then
                    local key = ZSRoom.getSquareKey(sq)
                    if key then
                        self.squares[key] = sq
                    end
                end
            end
        end
    end
    if not self:isValid() then return end
    
    self.airtight = false
    local validation = self:validate()
    self.airtight = validation and validation.allAirtight == true

    self.doors = nil -- invalidate doors cache
end

-- Get the room name
function ZSRoom:getName()
    local room = self.isoRoom
    if not room then return nil end

    local name = room.getName and room:getName() or nil
    if not name then name = tostring(room) end
    return name
end

