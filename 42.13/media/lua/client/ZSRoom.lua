-- Validate collected walls against airtight wall sets
function ZSRoom:validate()
    if not self:isValid() then
        return {
            valid = false,
            error = "Room is not valid"
        }
    end

    self.minX = nil
    self.maxX = nil
    self.minY = nil
    self.maxY = nil
    self.minZ = nil
    self.maxZ = nil

    local totalCount = 0
    for _ in pairs(self.squares) do
        totalCount = totalCount + 1
    end
    
    local result = {
        squares = {
            total = totalCount,
            withFloor = 0,
            withRoof = 0,
        }
    }

    -- Check if all squares have both floor and roof, calculate min/max X/Y
    for _, sq in pairs(self.squares) do
        if sq then
            local x, y, z = sq:getX(), sq:getY(), sq:getZ()

            if not self.minX or x < self.minX then
                self.minX = x
            end
            if not self.maxX or x > self.maxX then
                self.maxX = x
            end
            if not self.minY or y < self.minY then
                self.minY = y
            end
            if not self.maxY or y > self.maxY then
                self.maxY = y
            end
            if not self.minZ or z < self.minZ then
                self.minZ = z
            end
            if not self.maxZ or z > self.maxZ then
                self.maxZ = z
            end

            if sq:getFloor() then
                result.squares.withFloor = result.squares.withFloor + 1
            end
            local roofSq = getSquare(x, y, z + 1)
            if roofSq and roofSq:getFloor() then
                result.squares.withRoof = result.squares.withRoof + 1
            end
        end
    end

    self.width = self.maxX - self.minX + 1
    self.height = self.maxY - self.minY + 1

    if self.width > 0 and self.height > 0 then
        self.center = {
            x = self.minX + (self.width / 2),
            y = self.minY + (self.height / 2),
            z = self.minZ
        }
    end
    
    local nsWalls = self:getWallsDoorsNS()
    local ewWalls = self:getWallsDoorsEW()
    
    result.nsWalls = {
            total = #nsWalls,
            airtight = 0,
            tiles = {}
        }

    result.ewWalls = {
            total = #ewWalls,
            airtight = 0,
            tiles = {}
        }
    
    -- Use lookup tables for faster checking (O(1) instead of O(n))
    local airtightNS = ZSpaceship.MapData.AIRTIGHT_WALLS_NS_LOOKUP or {}
    local airtightEW = ZSpaceship.MapData.AIRTIGHT_WALLS_EW_LOOKUP or {}
    local airtightDoorsNS = ZSpaceship.MapData.AIRTIGHT_DOORS_NS_LOOKUP or {}
    local airtightDoorsEW = ZSpaceship.MapData.AIRTIGHT_DOORS_EW_LOOKUP or {}
    
    -- Validate N/S walls
    for _, wallData in ipairs(nsWalls) do
        local tileName = wallData.tileName
        -- Check both wall and door lookup tables
        local isAirtight = tileName and (airtightNS[tileName] == true or airtightDoorsNS[tileName] == true)

        table.insert(result.nsWalls.tiles, {
            x = wallData.x,
            y = wallData.y,
            z = wallData.z,
            direction = wallData.direction,
            tileName = tileName,
            airtight = isAirtight
        })
        
        if isAirtight then
            result.nsWalls.airtight = result.nsWalls.airtight + 1
        end
    end
    
    -- Validate E/W walls
    for _, wallData in ipairs(ewWalls) do
        local tileName = wallData.tileName
        -- Check both wall and door lookup tables
        local isAirtight = tileName and (airtightEW[tileName] == true or airtightDoorsEW[tileName] == true)
        
        table.insert(result.ewWalls.tiles, {
            x = wallData.x,
            y = wallData.y,
            z = wallData.z,
            direction = wallData.direction,
            tileName = tileName,
            airtight = isAirtight
        })
        
        if isAirtight then
            result.ewWalls.airtight = result.ewWalls.airtight + 1
        end
    end
    
    -- Overall validation: all walls must be airtight
    result.allAirtight = 
        result.squares.total > 0 and result.squares.total == result.squares.withFloor and result.squares.total == result.squares.withRoof and
        result.nsWalls.total > 0 and result.nsWalls.total == result.nsWalls.airtight and
        result.ewWalls.total > 0 and result.ewWalls.total == result.ewWalls.airtight and
        self.width > 0 and self.width * 2 == result.nsWalls.total and
        self.height > 0 and self.height * 2 == result.ewWalls.total
    
    return result
end

-- Get all non-airtight wall tiles
function ZSRoom:getNonAirtightTiles()
    if not self:isValid() then return {} end
    local walls = self:getWallsDoors()
    local nonAirtightTiles = {}
    local airtightNS = ZSpaceship.MapData.AIRTIGHT_WALLS_NS_LOOKUP or {}
    local airtightEW = ZSpaceship.MapData.AIRTIGHT_WALLS_EW_LOOKUP or {}
    local airtightDoorsNS = ZSpaceship.MapData.AIRTIGHT_DOORS_NS_LOOKUP or {}
    local airtightDoorsEW = ZSpaceship.MapData.AIRTIGHT_DOORS_EW_LOOKUP or {}
    for _, wallData in ipairs(walls) do
        local tileName = wallData.tileName
        local dir = wallData.direction
        local isNS = (dir == "north" or dir == "south")
        local isAirtight = tileName and (isNS and (airtightNS[tileName] == true or airtightDoorsNS[tileName] == true) or (airtightEW[tileName] == true or airtightDoorsEW[tileName] == true))
        if not isAirtight then
            table.insert(nonAirtightTiles, {
                square = wallData.square,
                x = wallData.x,
                y = wallData.y,
                z = wallData.z,
                wall = wallData.wall,
                tileName = tileName,
                direction = wallData.direction
            })
        end
    end
    return nonAirtightTiles
end

-- Collect all doors from the room (checking all boundary squares)
-- O(n) scan where n is the room perimeter, cached for O(1) subsequent retrievals
function ZSRoom:getDoors()
    if not self:isValid() then return {} end
    
    if self.doors then
        return self.doors
    end
    
    -- O(n) scan: only scans boundary squares (perimeter), each side checks one direction
    local doors = {}
    local seenDoors = {}
    
    -- Each side checks doors using sq:getDoor(bool)
    -- W/N doors: check on current square
    -- E/S doors: check on adjacent square (can't use getE()/getS() as they return null if door is closed)
    local sides = {
        {name = "north", squares = self:getSquaresN(), doorDir = true, checkOnAdj = false},
        {name = "south", squares = self:getSquaresS(), doorDir = true, checkOnAdj = true, dx = 0, dy = 1},
        {name = "east", squares = self:getSquaresE(), doorDir = false, checkOnAdj = true, dx = 1, dy = 0},
        {name = "west", squares = self:getSquaresW(), doorDir = false, checkOnAdj = false}
    }
    
    for _, sideInfo in ipairs(sides) do
        for _, sq in ipairs(sideInfo.squares) do
            local isoDoor = nil
            local adjSq = nil
            
            if sideInfo.checkOnAdj then
                -- For E/S: get adjacent square using coordinates and check door there
                if getSquare and sq then
                    local x, y, z = sq:getX(), sq:getY(), sq:getZ()
                    adjSq = getSquare(x + sideInfo.dx, y + sideInfo.dy, z)
                    if adjSq and adjSq.getDoor then
                        isoDoor = adjSq:getDoor(sideInfo.doorDir)
                    end
                end
            else
                -- For W/N: check door on current square
                if sq and sq.getDoor then
                    isoDoor = sq:getDoor(sideInfo.doorDir)
                    -- Get adjacent square for metadata
                    if getSquare then
                        local x, y, z = sq:getX(), sq:getY(), sq:getZ()
                        if sideInfo.name == "north" then
                            adjSq = getSquare(x, y - 1, z)
                        elseif sideInfo.name == "west" then
                            adjSq = getSquare(x - 1, y, z)
                        end
                    end
                end
            end
            
            if isoDoor then
                local doorKey = tostring(isoDoor)
                if not seenDoors[doorKey] then
                    seenDoors[doorKey] = true
                    local x, y, z = sq:getX(), sq:getY(), sq:getZ()
                    local adjX, adjY = adjSq and adjSq:getX() or (x + (sideInfo.dx or 0)), adjSq and adjSq:getY() or (y + (sideInfo.dy or 0))
                    local adjRoom = adjSq and adjSq:getRoom() or nil
                    
                    local doorTileName = nil
                    if isoDoor.getSpriteName then doorTileName = isoDoor:getSpriteName() elseif isoDoor.getTile then doorTileName = isoDoor:getTile() elseif isoDoor.getName then doorTileName = isoDoor:getName() end

                    local isOpen = false
                    if isoDoor.IsOpen then isOpen = isoDoor:IsOpen() end

                    local isExterior = false
                    if isoDoor.isExterior then isExterior = isoDoor:isExterior() end

                    table.insert(doors, {
                        isoDoor = isoDoor,
                        square = sq,
                        adjSquare = adjSq,
                        x = x,
                        y = y,
                        z = z,
                        adjX = adjX,
                        adjY = adjY,
                        direction = sideInfo.name,
                        tileName = doorTileName,
                        isExterior = isExterior,
                        isOpen = isOpen,
                        adjRoom = adjRoom,
                        hasFloor = (adjSq and adjSq.getFloor and adjSq:getFloor() ~= nil),
                        hasRoof = (adjSq and adjSq.getRoof and adjSq:getRoof() ~= nil)
                    })
                end
            end
        end
    end
    
    -- Cache the result for O(1) subsequent retrievals
    self.doors = doors
    self.doorsLastChecked = now
    
    return doors
end

-- Build connections for this room (which rooms it's connected to via doors)
-- Helper: Find adjacent room by checking further in direction
local function findAdjRoom(startSq, direction, currentRoom)
    local dirMap = {north = {0, -1}, south = {0, 1}, east = {1, 0}, west = {-1, 0}}
    local dx, dy = dirMap[direction][1], dirMap[direction][2]
    if not dx or not getSquare then return nil, startSq end
    
    local checkSq = startSq
    for i = 1, 5 do
        local x, y, z = checkSq:getX() + dx, checkSq:getY() + dy, checkSq:getZ()
        local nextSq = getSquare(x, y, z)
        if not nextSq then return nil, checkSq end
        
        local nextRoom = nextSq:getRoom()
        if nextRoom and nextRoom ~= currentRoom then return nextRoom, nextSq end
        if not nextRoom then return nil, nextSq end
        
        checkSq = nextSq
    end
    return nil, startSq
end

-- Helper: Find room by checking adjacent squares
local function findRoomNearSquare(sq, currentRoom)
    if not sq or not getSquare then return nil end
    local dirs = {{0, -1}, {-1, 0}, {0, 1}, {1, 0}}
    for _, dir in ipairs(dirs) do
        local checkSq = getSquare(sq:getX() + dir[1], sq:getY() + dir[2], sq:getZ())
        if checkSq then
            local room = checkSq:getRoom()
            if room and room ~= currentRoom then return room end
        end
    end
    return nil
end

function ZSRoom:buildConnections()
    if not self:isValid() then return end
    
    self.connections = {}
    local doors = self:getDoors()
    if not doors then return end
    
    for _, doorData in ipairs(doors) do
        local door = doorData.isoDoor
        local sq = doorData.square
        local adjSq = doorData.adjSquare
        if door and sq and adjSq then
            local adjRoom = ZSRooms.find(adjSq)
            
            if adjRoom and adjRoom ~= self then
                if not self.connections[adjRoom] then
                    self.connections[adjRoom] = {}
                end
                table.insert(self.connections[adjRoom], {isoDoor = door, square = sq, adjSquare = adjSq, adjRoom = adjRoom})
            end
        end
    end
end

-- Check if room is breached (uses cached vacuum state)
function ZSRoom:isBreached()
    if not self:isValid() or not self.isoRoom then
        return true
    end
    
    -- Return cached vacuum state (calculated by updateAllFast)
    -- If not calculated yet, default to false (sealed)
    return self.vacuumState == ZSRoom.State.BREACHED
end

function ZSRoom:isAllDoorsClosed()
    if not self:isValid() or not self.isoRoom then
        return false
    end
    
    local doors = self:getDoors()
    if not doors then return true end
    
    for _, door in ipairs(doors) do
        if door.isOpen then return false end
    end
    return true
end