-- Get wall tiles on the north side
function ZSRoom:getWallsDoorsN()
    local northSquares = self:getSquaresN()
    local walls = {}
    
    for _, sq in ipairs(northSquares) do
        local x, y, z = sq:getX(), sq:getY(), sq:getZ()
        -- Check for wall on the north side of this square
        -- true = north wall
        local wall = sq:getWall(true) or sq:getDoor(true)
        if wall then
            local tileName = nil
            if wall.getSpriteName then
                tileName = wall:getSpriteName()
            elseif wall.getTile then
                tileName = wall:getTile()
            elseif wall.getName then
                tileName = wall:getName()
            end
            
            table.insert(walls, {
                square = sq,
                x = x,
                y = y,
                z = z,
                wall = wall,
                tileName = tileName
            })
        end
    end
    
    return walls
end

